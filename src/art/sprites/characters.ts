import { bob, patch, sprite, type SpriteDef } from '../sprite';

/**
 * 祓い手（16×24・右向き・足元が原点）。
 * フレーム 0 は立ち姿。歩行中は全フレームを順に繰り返す。
 * 歩行は「立ち → 左足を上げる → 立ち → 右足を上げる」の 4 コマ。
 * 足を上げるコマは、上半身を 1px 沈め（bob）、下端 4 行の足を差し替えて（patch）作る。
 */

/** 足を上げたコマを作る：下端 4 行（足）を差し替え、それより上を 1px 沈める */
function step(src: string, legs: string[]): string {
  return patch(bob(src, 4), 20, legs);
}

/** 立ち姿と左右の足から、4 コマの歩行つきスプライトを作る */
function character(id: string, stand: string, left: string[], right: string[]): SpriteDef {
  return sprite(id, 16, 24, [stand, step(stand, left), stand, step(stand, right)]);
}

